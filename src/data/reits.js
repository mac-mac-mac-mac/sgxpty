// SGX S-REIT reference data — identity labels and hand-entered Five-Filter ratings ONLY.
// Everything numeric about the market (price, yield, DPU growth, distribution status,
// P/NAV, gearing estimate) is calculated nightly by scripts/fetch-prices.mjs and merged in
// by src/lib/yahooFinance.js. Do not add market data here.
//
// Five-filter ratings: asset (30%), debt (25%), dpu (25%), manager (10%), valuation (10%); each 1-5.

function calcComposite(r) {
  return +(
    r.asset * 0.30 +
    r.debt * 0.25 +
    r.dpu * 0.25 +
    r.manager * 0.10 +
    r.valuation * 0.10
  ).toFixed(1);
}

// Risk-free benchmark for the yield-spread check (percent). Still hand-entered.
export const RISK_FREE_RATE = 2.1;

// Beansprout-style 3-check screen. Any missing input means the REIT cannot pass.
export function evaluateThreeChecks(reit) {
  const { dpuGrowth, gearing, yield: yieldPct } = reit;
  if (dpuGrowth == null || gearing == null || yieldPct == null) {
    return { dpuStatus: '—', gearingStatus: '—', yieldStatus: '—', yieldSpread: null, passesAll: false };
  }
  const dpuStatus = dpuGrowth >= 0 ? '✅ Growing/Stable' : '⚠️ Declining';
  const gearingStatus = gearing < 40 ? '✅ Strong' : gearing < 45 ? '⚠️ Acceptable' : '❌ High';
  const spread = yieldPct - RISK_FREE_RATE;
  const yieldSpread = spread.toFixed(1);
  const yieldStatus = spread > 3 ? '✅ Attractive' : spread > 1.5 ? '⚠️ Fair' : '❌ Low';
  const passesAll = dpuGrowth >= 0 && gearing < 45 && spread > 1.5;
  return { dpuStatus, gearingStatus, yieldStatus, yieldSpread, passesAll };
}

